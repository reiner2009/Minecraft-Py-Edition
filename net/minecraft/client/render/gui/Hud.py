def render_wallpaper(name):
    glMatrixMode(GL_MODELVIEW)
    glLoadIdentity()
    glDisable(GL_DEPTH_TEST)
    glEnable(GL_TEXTURE_2D)
    glColor4f(1,1,1,1)
    glBindTexture(GL_TEXTURE_2D, name)
    uv=[(0,1),(1,1),(1,0),(0,0)]
    glBegin(GL_QUADS)
    glTexCoord2fv(uv[0])
    glVertex2f(0,0)
    glTexCoord2fv(uv[1])
    glVertex2f(width,0)
    glTexCoord2fv(uv[2])
    glVertex2f(width,height)
    glTexCoord2fv(uv[3])
    glVertex2f(0,height)
    glEnd()

